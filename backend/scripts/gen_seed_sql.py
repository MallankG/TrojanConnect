"""Generate supabase/seed.sql from the JSON seeds in app/repositories/seed/ so the in-memory
demo data and the Supabase demo data stay identical.

Usage (from backend/):  python scripts/gen_seed_sql.py
Re-run after editing clubs.json / events.json / students.json. The output is idempotent
(upserts), so it can be applied repeatedly; events are re-dated relative to now()."""
from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.schemas.student import ClubProfile, StudentPreferences  # noqa: E402

SEED_DIR = BACKEND / "app" / "repositories" / "seed"
OUT = BACKEND.parent / "supabase" / "seed.sql"
TZ = "America/Los_Angeles"
JSONB_FIELDS = {"tags", "activities", "notable_events", "faq", "interest_tags"}


def lit(value) -> str:
    """SQL literal for a python value."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, dict)):
        return lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def upsert(table: str, row: dict, conflict: str) -> str:
    cols = list(row)
    updates = [c for c in cols if c not in conflict.split(",")]
    action = ("do update set " + ", ".join(f"{c} = excluded.{c}" for c in updates)) if updates else "do nothing"
    values = ",\n    ".join(lit(row[c]) for c in cols)
    return (f"insert into {table} ({', '.join(cols)}) values (\n    {values}\n)\n"
            f"on conflict ({conflict}) {action};\n")


def main() -> None:
    clubs = [ClubProfile.model_validate(c) for c in json.loads((SEED_DIR / "clubs.json").read_text("utf-8"))]
    events = json.loads((SEED_DIR / "events.json").read_text("utf-8"))
    students = json.loads((SEED_DIR / "students.json").read_text("utf-8"))
    club_ids = {c.organization_id for c in clubs}

    out = [
        "-- GENERATED by backend/scripts/gen_seed_sql.py from backend/app/repositories/seed/*.json.",
        "-- Do not edit by hand; edit the JSON and re-run the script.",
        "-- Demo data only: fictional clubs, students and events (data_label = 'demo').",
        "-- Apply after supabase/migrations/0001_student_agent.sql. Safe to re-run.",
        "",
        "begin;",
        "",
        "-- ---------- organizations + club profiles ----------",
    ]
    for c in clubs:
        out.append(upsert("organizations", {
            "id": c.organization_id, "name": c.name, "type": "club",
            "description": c.public_description, "verification_status": c.verification_status,
        }, "id"))
        row = c.model_dump(mode="json")
        for key in JSONB_FIELDS & row.keys():
            row[key] = list(row[key])
        out.append(upsert("club_profiles", row, "organization_id"))

    out.append("-- ---------- events (re-dated relative to now(), campus-local start hour) ----------")
    for e in events:
        if e["organization_id"] not in club_ids:
            raise SystemExit(f"event {e['id']} references unknown club {e['organization_id']}")
        start_minutes = int(round(float(e["start_hour"]) * 60))
        dur_minutes = int(round(float(e["duration_hours"]) * 60))
        start = (f"((date_trunc('day', now() at time zone '{TZ}') + interval '{int(e['days_from_now'])} days'"
                 f" + interval '{start_minutes} minutes') at time zone '{TZ}')")
        cols = ["id", "organization_id", "title", "description", "location", "visibility"]
        vals = ", ".join(lit(e.get(c, "")) for c in cols)
        out.append(
            f"insert into events ({', '.join(cols)}, timezone, start_at, end_at) values (\n"
            f"    {vals}, '{TZ}',\n    {start},\n    {start} + interval '{dur_minutes} minutes'\n)\n"
            "on conflict (id) do update set organization_id = excluded.organization_id, title = excluded.title, "
            "description = excluded.description, location = excluded.location, visibility = excluded.visibility, "
            "timezone = excluded.timezone, start_at = excluded.start_at, end_at = excluded.end_at;\n")

    out.append("-- ---------- demo students ----------")
    for s in students:
        out.append(upsert("profiles", {
            "id": s["user_id"], "display_name": s.get("display_name", ""), "email": s.get("email", ""),
        }, "id"))
        if s.get("preferences"):
            prefs = StudentPreferences(user_id=s["user_id"], **s["preferences"]).model_dump(mode="json")
            prefs.pop("updated_at")
            out.append(upsert("student_preferences", prefs, "user_id"))

    out.append("commit;\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({len(clubs)} clubs, {len(events)} events, {len(students)} students)")


if __name__ == "__main__":
    main()
