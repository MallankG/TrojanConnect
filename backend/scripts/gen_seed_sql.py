"""Generate supabase/seed.sql from the JSON seeds so the in-memory repository and Supabase
serve the SAME dataset. Generating from the demo seed while the app serves the collected
one leaves every organization_id different and breaks the foreign keys.

Usage (from backend/):  python scripts/gen_seed_sql.py [auto|demo|real]
  auto (default) - whichever dataset the app would serve (SEED_DATASET / files present)
  demo           - invented sample clubs
  real           - clubs collected from public pages (rich profiles + directory tier)

Re-run after editing the seed JSON. Output is idempotent (upserts). Demo events are
re-dated relative to now(); collected events carry their own absolute timestamps."""
from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.repositories.memory import load_seed_clubs, resolve_dataset  # noqa: E402
from app.schemas.student import ClubProfile, StudentPreferences  # noqa: E402

SEED_DIR = BACKEND / "app" / "repositories" / "seed"
REAL_SEED_DIR = SEED_DIR / "real"
# demo -> supabase/seed.sql (committed, small). real -> supabase/seed.real.sql, which is
# ~5 MB for the whole EngageSC directory and is gitignored: regenerate it when you need it.
OUT_BY_DATASET = {"demo": BACKEND.parent / "supabase" / "seed.sql",
                  "real": BACKEND.parent / "supabase" / "seed.real.sql"}
TZ = "America/Los_Angeles"
JSONB_FIELDS = {"tags", "activities", "notable_events", "faq", "interest_tags", "social_links", "source_urls"}


def lit(value) -> str:
    """SQL literal for a python value."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, dict)):
        return lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def upsert(table: str, row: dict, conflict: str) -> str:
    cols = list(row)
    updates = [c for c in cols if c not in conflict.split(",")]
    action = ("do update set " + ", ".join(f"{c} = excluded.{c}" for c in updates)) if updates else "do nothing"
    values = ",\n    ".join(lit(row[c]) for c in cols)
    return (f"insert into {table} ({', '.join(cols)}) values (\n    {values}\n)\n"
            f"on conflict ({conflict}) {action};\n")


def main() -> None:
    requested = next((a for a in sys.argv[1:] if not a.startswith("-")), "auto")
    if requested not in {"auto", "demo", "real"}:
        raise SystemExit(f"unknown dataset {requested!r}; use auto, demo or real")
    dataset = resolve_dataset(requested)
    out_path = OUT_BY_DATASET[dataset]
    seed_dir = REAL_SEED_DIR if dataset == "real" else SEED_DIR

    clubs = sorted(load_seed_clubs(dataset), key=lambda c: c.organization_id)
    events_path = seed_dir / "events.json"
    events = json.loads(events_path.read_text("utf-8")) if events_path.is_file() else []
    students = json.loads((SEED_DIR / "students.json").read_text("utf-8"))
    club_ids = {c.organization_id for c in clubs}
    events = [e for e in events if e["organization_id"] in club_ids]

    out = [
        "-- GENERATED by backend/scripts/gen_seed_sql.py from backend/app/repositories/seed/*.json.",
        "-- Do not edit by hand; edit the JSON and re-run the script.",
        f"-- Dataset: {dataset}."
        + (" Invented sample clubs (data_label = 'demo')." if dataset == "demo"
           else " Clubs collected from public web pages (data_label = 'public_web'); demo students only."),
        "-- Apply after supabase/migrations/0001_student_agent.sql. Safe to re-run.",
        "",
        "begin;",
        "",
        "-- ---------- organizations + club profiles ----------",
    ]
    for c in clubs:
        out.append(upsert("organizations", {
            "id": c.organization_id, "name": c.name, "type": "club",
            "description": c.public_description, "verification_status": c.verification_status,
        }, "id"))
        row = c.model_dump(mode="json")
        for key in JSONB_FIELDS & row.keys():
            row[key] = list(row[key])
        out.append(upsert("club_profiles", row, "organization_id"))

    out.append("-- ---------- events ----------")
    for e in events:
        if "start_at" in e:  # collected event: absolute timestamps
            cols = ["id", "organization_id", "title", "description", "location", "visibility"]
            row = {c: e.get(c, "") for c in cols}
            row["id"] = e.get("id") or f"{e['organization_id']}-{abs(hash(e['title'])) % 10**8}"
            row["timezone"] = e.get("timezone") or TZ
            row["start_at"], row["end_at"] = e["start_at"], e["end_at"]
            out.append(upsert("events", row, "id"))
            continue
        start_minutes = int(round(float(e["start_hour"]) * 60))
        dur_minutes = int(round(float(e["duration_hours"]) * 60))
        start = (f"((date_trunc('day', now() at time zone '{TZ}') + interval '{int(e['days_from_now'])} days'"
                 f" + interval '{start_minutes} minutes') at time zone '{TZ}')")
        cols = ["id", "organization_id", "title", "description", "location", "visibility"]
        vals = ", ".join(lit(e.get(c, "")) for c in cols)
        out.append(
            f"insert into events ({', '.join(cols)}, timezone, start_at, end_at) values (\n"
            f"    {vals}, '{TZ}',\n    {start},\n    {start} + interval '{dur_minutes} minutes'\n)\n"
            "on conflict (id) do update set organization_id = excluded.organization_id, title = excluded.title, "
            "description = excluded.description, location = excluded.location, visibility = excluded.visibility, "
            "timezone = excluded.timezone, start_at = excluded.start_at, end_at = excluded.end_at;\n")

    out.append("-- ---------- demo students ----------")
    for s in students:
        out.append(upsert("profiles", {
            "id": s["user_id"], "display_name": s.get("display_name", ""), "email": s.get("email", ""),
        }, "id"))
        if s.get("preferences"):
            prefs = StudentPreferences(user_id=s["user_id"], **s["preferences"]).model_dump(mode="json")
            prefs.pop("updated_at")
            out.append(upsert("student_preferences", prefs, "user_id"))

    out.append("commit;\n")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {out_path} from the {dataset} dataset "
          f"({len(clubs)} clubs, {len(events)} events, {len(students)} students)")


if __name__ == "__main__":
    main()
